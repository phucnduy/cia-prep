// Builds a local must/should list of GIAS from the full official text, so question writers can check
// whether a rule is mandatory (Requirements, "must") or guidance (Considerations, "should").
// Output stays outside the repo (GIAS text is copyrighted): ~/.claude/skills/internal-audit/references/gias-must-should.md
// Usage: node scripts/gias-must-should.mjs
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';

const DIR = `${homedir()}/.claude/skills/internal-audit/references`;
const SRC = `${DIR}/gias-official-full.txt`;
const OUT = `${DIR}/gias-must-should.md`;
if (!existsSync(SRC)) {
  console.error(`GIAS text not found: ${SRC}`);
  process.exit(1);
}

// pdftotext adds form feeds and repeats the domain name as a page footer; drop both.
const FOOTER = /^(I|II|III|IV|V): [A-Z]/;
const lines = readFileSync(SRC, 'utf8').split('\n').map((l) => l.replace(/\f/g, '').trimEnd()).filter((l) => !FOOTER.test(l));

const SECTION = {
  Requirements: 'req',
  'Essential Conditions': 'ess',
  'Considerations for Implementation': 'con',
  'Examples of Evidence of Conformance': 'ev',
};
// A heading is "Standard x.y Title" (no dot leaders, not a "(See also ...)" tail ending in ".)").
// Titles may wrap and end in a comma (9.1), so accept those when "Requirements" follows shortly.
const isStandard = (l, k) =>
  /^Standard \d+\.\d+ /.test(l) &&
  !l.includes('....') &&
  l.length < 90 &&
  !/[.;)]$/.test(l) &&
  (!l.endsWith(',') || lines.slice(k + 1, k + 4).includes('Requirements'));
const isStop = (l) => /^(Principle \d+ |Domain [IV]+|Glossary\b)/.test(l);

// Group the text into standards and sections.
const standards = [];
let cur = null;
let sec = null;
for (const [k, l] of lines.entries()) {
  if (isStandard(l, k)) {
    // Join a wrapped title (e.g. 9.1, 4.1) with its second line.
    const next = lines[k + 1] || '';
    const title = !SECTION[next] && next && next.length < 60 && !/[.:]$/.test(next) ? `${l} ${next}` : l;
    cur = { title, req: [], ess: [], con: [], ev: [], skip: title !== l };
    standards.push(cur);
    sec = 'req'; // a few standards lost the "Requirements" heading in extraction
    continue;
  }
  if (cur?.skip) {
    cur.skip = false; // second line of a wrapped title
    continue;
  }
  if (!cur) continue;
  if (SECTION[l]) {
    sec = SECTION[l];
    continue;
  }
  if (isStop(l)) {
    cur = null;
    continue;
  }
  if (l.trim()) cur[sec].push(l.trim());
}

// Join wrapped lines into items: a bullet starts a new item; other lines continue the previous one.
// A plain line after a finished bullet (previous line ends in '.') starts new prose, and the
// Essential Conditions group names (Board, Senior Management) stand alone.
const GROUP = /^(Board|Senior Management|Chief Audit Executive)$/;
const items = (ls) => {
  const out = [];
  let prev = '';
  for (const l of ls) {
    const last = out[out.length - 1] || '';
    const newProse = /^[•–]/.test(last) && /\.\)?$/.test(prev) && /^[A-Z]/.test(l);
    if (/^[•–]/.test(l) || !out.length || newProse || GROUP.test(l) || GROUP.test(last)) out.push(l);
    else out[out.length - 1] += ' ' + l;
    prev = l;
  }
  return out;
};
// Split prose items into sentences; keep bullets that follow a sentence ending in ':' with that sentence.
const statements = (ls) => {
  const out = [];
  for (const it of items(ls)) {
    if (/^[•–]/.test(it) && out.length && /:\s*$|:\n/.test(out[out.length - 1])) {
      out[out.length - 1] += '\n  ' + it;
      continue;
    }
    if (/^[•–]/.test(it) && out.length && out[out.length - 1].includes('\n  ')) {
      out[out.length - 1] += '\n  ' + it;
      continue;
    }
    for (const s of it.split(/(?<=[.?!])\s+(?=[A-Z(])/)) out.push(s);
  }
  return out;
};

const has = (word) => (s) => new RegExp(`\\b${word}\\b`, 'i').test(s);
const bullet = (s) => `- ${s.replace(/^[•–]\s*/, '')}`;
let mustCount = 0;
let shouldCount = 0;
const md = [
  '# GIAS 2024: must vs should',
  '',
  'Generated by `node scripts/gias-must-should.mjs` from gias-official-full.txt. Do not edit by hand.',
  '',
  '- **MUST**: sentences with "must" in the Requirements block. Mandatory; a question may test them as rules.',
  '- **SHOULD**: sentences with "should" in Considerations for Implementation. Guidance, not a requirement; never write "GIAS requires" for these.',
  '- **Essential Conditions**: what the board and senior management are expected to do. Not requirements of internal auditors; the CAE discusses them with the board.',
  '- **Check also** lists "should" found inside Requirements and "must" found inside Considerations (rare; read in context).',
  '',
];
for (const st of standards) {
  const req = statements(st.req);
  const con = statements(st.con);
  const must = req.filter(has('must'));
  const should = con.filter(has('should'));
  const odd = [...req.filter(has('should')).map((s) => `(Requirements) ${s}`), ...con.filter(has('must')).map((s) => `(Considerations) ${s}`)];
  mustCount += must.length;
  shouldCount += should.length;
  md.push(`## ${st.title}`, '');
  md.push('**MUST**', '', ...(must.length ? must.map(bullet) : ['- (none found; read the standard)']), '');
  if (should.length) md.push('**SHOULD**', '', ...should.map(bullet), '');
  if (st.ess.length) md.push('**Essential Conditions**', '', ...items(st.ess).map((s) => (/^[•–]/.test(s) ? bullet(s) : `*${s}*`)), '');
  if (odd.length) md.push('**Check also**', '', ...odd.map(bullet), '');
}
writeFileSync(OUT, md.join('\n') + '\n');
console.log(`${standards.length} standards, ${mustCount} must, ${shouldCount} should -> ${OUT}`);
